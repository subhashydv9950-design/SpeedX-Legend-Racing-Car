  function init() {
    const saved = getSettingsLanguage();
    setLanguage(translations[saved] ? saved : "en");

    document.addEventListener("change", event => {
      const selector = event.target.closest("[data-language-selector]");

      if (!selector) return;

      setLanguage(selector.value);

      if (SX.settingsManager) {
        SX.settingsManager.set("language", selector.value);
      }
    });
  }

