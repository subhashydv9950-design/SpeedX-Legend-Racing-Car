  let activeLanguage = "en";

  function getSettingsLanguage() {
    if (SX.settingsManager && SX.settingsManager.get) {
      return SX.settingsManager.get("language") || "en";
    }

    if (SX.settings && SX.settings.language) {
      return SX.settings.language;
    }

    return "en";
  }

  function setLanguage(language) {
    const code = String(language || "en").toLowerCase();

    if (!translations[code]) {
      console.warn("SUPERX: Language not available:", code);
      return false;
    }

    activeLanguage = code;

    document.documentElement.lang = code;

    if (document.documentElement.dir !== "rtl") {
      document.documentElement.dir = "ltr";
    }

    translatePage();

    window.dispatchEvent(
      new CustomEvent("superx:language-changed", {
        detail: { language: code }
      })
    );

    return true;
  }

  function getLanguage() {
    return activeLanguage;
  }

  function translate(key, fallback) {
    const dictionary = translations[activeLanguage] || translations.en;

    if (dictionary[key] !== undefined) {
      return dictionary[key];
    }

    if (translations.en[key] !== undefined) {
      return translations.en[key];
    }

    return fallback !== undefined ? fallback : key;
  }

  function translatePage(root = document) {
    root.querySelectorAll("[data-i18n]").forEach(element => {
      const key = element.dataset.i18n;
      const translated = translate(key);

      if (element.dataset.i18nAttribute) {
        const attribute = element.dataset.i18nAttribute;
        element.setAttribute(attribute, translated);
      } else {
        element.textContent = translated;
      }
    });

    root.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
      element.placeholder = translate(
        element.dataset.i18nPlaceholder
      );
    });

    root.querySelectorAll("[data-i18n-title]").forEach(element => {
      element.title = translate(element.dataset.i18nTitle);
    });
  }
